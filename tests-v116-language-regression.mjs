import assert from 'node:assert/strict';
import {resolveSubject114,canonicalGrades114} from './v10/education-scope114.js';

const cases=[
 ['سويت تحليل نتايج عربي اول متوسط','متوسط',['الأول المتوسط'],'اللغة العربية'],
 ['حللت نتائج عربية ثاني متوسط','متوسط',['الثاني المتوسط'],'اللغة العربية'],
 ['تحليل نتايج لغتي اول متوسط','متوسط',['الأول المتوسط'],'اللغة العربية'],
 ['تحليل نتائج انجليزي اول متوسط','متوسط',['الأول المتوسط'],'اللغة الإنجليزية'],
 ['تحليل نتايج انقليزي ثاني متوسط','متوسط',['الثاني المتوسط'],'اللغة الإنجليزية'],
 ['تحليل نتائج اغليز ثالث متوسط','متوسط',['الثالث المتوسط'],'اللغة الإنجليزية'],
 ['تحليل نتائج فنية اول متوسط','متوسط',['الأول المتوسط'],'التربية الفنية'],
 ['تحليل نتائج بدنية اول متوسط','متوسط',['الأول المتوسط'],'التربية البدنية والدفاع عن النفس'],
 ['تحليل نتائج اجتماعيات ثاني متوسط','متوسط',['الثاني المتوسط'],'الدراسات الاجتماعية'],
 ['تحليل نتائج حاسب اول متوسط','متوسط',['الأول المتوسط'],'المهارات الرقمية'],
 ['تحليل نتائج التقنية الرقمية 1 اول ثانوي','ثانوي',['الأول الثانوي'],'التقنية الرقمية 1'],
 ['تحليل نتائج احياء اول ثانوي','ثانوي',['الأول الثانوي'],'الأحياء 1']
];
for(const [raw,stage,grades,expected] of cases){
 const state={raw,stage,grades:canonicalGrades114(stage,grades),metadata:{semantic101:{stage,grades}}};
 const got=resolveSubject114(state)?.name;
 assert.equal(got,expected,`${raw} -> ${got} expected ${expected}`);
}
assert.deepEqual(canonicalGrades114('متوسط',['اول','الأول المتوسط']),['الأول المتوسط']);
assert.deepEqual(canonicalGrades114('ثانوي',['اول','الأول الثانوي']),['الأول الثانوي']);
console.log(`V116 language regression passed: ${cases.length} subject phrases + canonical grade checks.`);
